def build_messages(pkg: EvidencePackage) -> list[dict]:
    pids = ", ".join(sorted(pkg.patient_evidence_ids))
    gids = ", ".join(p.citation_id for p in pkg.guideline_passages) or "none"
    user = (
        f"{render_patient_evidence(pkg)}\n\n{render_guideline_passages(pkg)}\n\n"
        f"Valid patient evidence IDs: {pids}\nValid guideline passage IDs: {gids}\n\n"
        f"Clinician question: {pkg.question}\n\n"
        "Write the review as the JSON object described. Return only the JSON object."
    )
    return [{"role": "system", "content": SYSTEM_PROMPT}, {"role": "user", "content": user}]


