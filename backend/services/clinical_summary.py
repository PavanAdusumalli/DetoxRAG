def contextual_limitations(pkg: EvidencePackage) -> list[str]:
    t = pkg.timeline
    out = []
    if t.documentation_gaps:
        out.append(f"{len(t.documentation_gaps)} documentation gap(s) were identified in the retrieved record (listed separately).")
    if t.documentation_conflicts:
        out.append(f"{len(t.documentation_conflicts)} possible documentation conflict(s) were flagged; the summary does not determine which record is correct.")
    if "record begins at admission" in t.window.label:
        out.append(f"The requested window extends before admission; only {t.window.hours:g} h of record are available.")
    if pkg.retrieval_mode == "none":
        out.append("Guideline retrieval was disabled for this request.")
    elif not pkg.guideline_passages:
        out.append("No sufficiently relevant guideline passages were retrieved.")
    return out


def _parse(text: str) -> RawSummary | None:
    obj = extract_json_object(text)
    if obj is None:
        return None
    try:
        return RawSummary.model_validate(obj)
    except ValidationError:
        return None


def summarize_package(pkg: EvidencePackage, llm: LLM, max_tokens: int = 900) -> ClinicalSummaryResponse:
    t = pkg.timeline
    report = ValidationReport()
    warnings: list[str] = []
    timings: dict[str, float] = {}
    tokens: dict[str, int] = {}

    messages = build_messages(pkg)
    t0 = time.perf_counter()
    res = llm.generate(messages, max_tokens=max_tokens)
    raw = _parse(res.text)
    tokens = {"prompt": res.prompt_tokens, "generated": res.generation_tokens}
    if raw is None:
        report.json_valid_first_try = False
        warnings.append("First model output was not valid JSON; regenerated once.")
        retry = messages + [
            {"role": "assistant", "content": res.text},
            {"role": "user", "content": "That was not a valid JSON object with the required fields. Return only the JSON object."},
        ]
        res = llm.generate(retry, max_tokens=max_tokens)
        tokens["generated"] += res.generation_tokens
        raw = _parse(res.text)
    timings["generation"] = round((time.perf_counter() - t0) * 1000, 1)

    base = dict(
        patient_id=pkg.patient_id,
        booking_number=pkg.booking_number,
        withdrawal_type=pkg.withdrawal_type,
        monitoring_type=pkg.monitoring_type,
        time_window=t.window,
        question=pkg.question,
        retrieval_mode=pkg.retrieval_mode,
        guideline_query=pkg.guideline_query,
        documentation_gaps=[g.description for g in t.documentation_gaps],
        documentation_conflicts=[c.description for c in t.documentation_conflicts],
        score_summary=t.score_summary,
        intervals=t.intervals,
        retrieved_passages=pkg.guideline_passages,
        timings_ms=timings,
        llm_tokens=tokens,
    )

    if raw is None:
        msg = "The model did not return a valid structured summary. Review the records and computed facts directly."
        return ClinicalSummaryResponse(
            **base, patient_summary=msg, assessment_trend="", vital_sign_observations="",
            medication_documentation="", guideline_context="", patient_evidence=[], guideline_citations=[],
            limitations=contextual_limitations(pkg) + STANDARD_LIMITATIONS, validation=report,
            warnings=warnings + ["Model output could not be parsed as JSON."], generated=False,
        )

    patient_ids = pkg.patient_evidence_ids
    guideline_ids = pkg.guideline_ids
    self_refs = {pkg.patient_id, pkg.booking_number}
    base["raw_model_output"] = raw.model_dump()
    fields: dict[str, str] = {}
    cited_patient: list[str] = []
    cited_guideline: list[str] = []
    nums_ok = allowed_numbers(pkg)

    for name in TEXT_SECTIONS:
        text = getattr(raw, name)
        # Patient sections may cite only patient evidence; guideline context only passages.
        allowed = patient_ids if name in PATIENT_SECTIONS else guideline_ids
        placeholders = re.findall(r"<[^<>]{1,40}>", text)
        if placeholders:
            report.template_placeholders += len(placeholders)
            text = re.sub(r"(?<=[.!?])\s+", "\n", text)
            text = " ".join(s for s in text.split("\n") if not re.search(r"<[^<>]{1,40}>", s))
        if name in PATIENT_SECTIONS:
            text = _remove_flagged_sentences(text, report, name)
            text, failures = fact_check_section(name, text, t)
            report.fact_check_failures.extend(failures)
        clean, cited = validate_section(text, allowed, self_refs, report, name)
        fields[name] = clean
        target = cited_patient if name in PATIENT_SECTIONS else cited_guideline
        target.extend(c for c in cited if c not in target)
        if name in PATIENT_SECTIONS:
            n, u = count_uncited(clean)
            report.n_sentences += n
            report.n_uncited_sentences += u
            for num in sorted(value_numbers(clean)):
                # Accept exact values and the model rounding them (44 for 44.02 h).
                if num in nums_ok or any(num == round(e) or num == round(e, 1) for e in nums_ok):
                    continue
                report.unsupported_numbers.append(f"{name}: {num:g}")

    if not pkg.guideline_passages:
        fields["guideline_context"] = "No guideline passages were retrieved for this request."

    if report.invalid_citations:
        warnings.append(f"Removed citation(s) not present in the supplied evidence: {', '.join(report.invalid_citations)}")
    if report.redacted_identifiers:
        warnings.append(f"Redacted identifier(s) of other patients/bookings: {', '.join(sorted(set(report.redacted_identifiers)))}")
    if report.unsupported_numbers:
        warnings.append("Value(s) not found in the patient evidence (verify): " + "; ".join(report.unsupported_numbers))
    if report.n_uncited_sentences:
        warnings.append(f"{report.n_uncited_sentences} of {report.n_sentences} patient-record sentence(s) have no citation.")
    if report.removed_sentences:
        warnings.append(f"Removed {len(report.removed_sentences)} sentence(s) containing severity classification or "
                        "recommendation wording: " + " | ".join(report.removed_sentences))
    if report.fact_check_failures:
        warnings.append(
            f"Replaced {len(report.fact_check_failures)} model claim(s) contradicted by the computed analytics: "
            + "; ".join(f"{f.claim} stated {f.stated}, record shows {f.expected}" for f in report.fact_check_failures))
    if report.template_placeholders:
        warnings.append(f"Removed {report.template_placeholders} unfilled template placeholder(s) from the model output.")
    if report.interpretation_flags:
        warnings.append("Interpretive wording to verify: " + " | ".join(report.interpretation_flags))

    by_eid = {e.evidence_id: e for e in pkg.patient_evidence}
    by_gid = {p.citation_id: p for p in pkg.guideline_passages}
    limitations = contextual_limitations(pkg) + STANDARD_LIMITATIONS
    return ClinicalSummaryResponse(
        **base,
        **fields,
        patient_evidence=[by_eid[i] for i in cited_patient],
        guideline_citations=[to_citation(by_gid[i]) for i in cited_guideline],
        limitations=limitations,
        validation=report,
        warnings=warnings,
    )


def generate_clinical_summary(
    conn: sqlite3.Connection,
    patient_id: str,
    question: str,
    llm: LLM,
    retriever: Retriever | None = None,
    booking_number: str | None = None,
    hours: float | None = None,
    retrieval_mode: str = "hybrid",
    k: int = 4,
) -> ClinicalSummaryResponse:
    question = question.strip()
    if not question:
        raise ValueError("Question must not be empty")
    if len(question) > 1000:
        raise ValueError("Question is too long (max 1000 characters)")
    t0 = time.perf_counter()
    pkg = build_evidence_package(conn, patient_id, question, booking_number, hours, retriever, retrieval_mode, k)
    evidence_ms = round((time.perf_counter() - t0) * 1000, 1)
    out = summarize_package(pkg, llm)
    out.timings_ms = {"evidence_and_retrieval": evidence_ms, **out.timings_ms,
                      "total": round((time.perf_counter() - t0) * 1000, 1)}
    return out
