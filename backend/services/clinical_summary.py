"""Grounded patient-review summaries with the local Qwen3 model.

Pipeline: evidence package -> controlled prompt -> JSON from the model ->
validation -> structured response. Code (not the model) supplies:
patient identity, monitoring type, time window, the documentation-gap list,
conflict flags, standard limitations and the disclaimer.

Validation performed on the model output:
  * JSON schema (one regeneration on failure; safe fallback after that);
  * every inline [ID] must be a supplied patient-evidence ID or retrieved
    guideline passage ID — anything else is removed and reported;
  * identifiers of *other* patients/bookings are redacted (leakage guard);
  * numbers in patient-facing text that do not occur in the patient evidence
    are reported as possibly unsupported;
  * sentences without any valid citation are counted;
  * wording that looks like a clinical classification or recommendation is
    flagged for review.
"""

