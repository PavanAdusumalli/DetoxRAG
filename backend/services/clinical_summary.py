# Validation helpers
# --------------------------------------------------------------------------- #


def _numbers(text: str) -> set[float]:
    out = set()
    for m in NUMBER_RE.findall(text):
        try:
            out.add(abs(float(m)))
        except ValueError:
            pass
    return out


def value_numbers(text: str) -> set[float]:
    """Numbers that represent values: IDs, dates and clock times removed."""
    text = BRACKET_RE.sub(" ", text)
    text = ID_TOKEN_RE.sub(" ", text)
    text = DATETIME_RE.sub(" ", text)
    return _numbers(text)


def allowed_numbers(pkg: EvidencePackage) -> set[float]:
    return value_numbers(render_patient_evidence(pkg) + " " + pkg.question) | {0.0, 1.0}


def _bare_ids_to_brackets(text: str, allowed_ids: set[str]) -> str:
    """Treat a valid ID written without brackets ("as per BJA-2023-0152") as a citation.
    IDs already inside a [...] span are left alone."""
    spans = [(m.start(), m.end()) for m in re.finditer(r"\[[^\]]*\]", text)]

    def repl(m: re.Match) -> str:
        if any(a <= m.start() < b for a, b in spans):
            return m.group(0)
        return f"[{m.group(0)}]" if m.group(0) in allowed_ids else m.group(0)
    return ID_TOKEN_RE.sub(repl, text)


def _remove_flagged_sentences(text: str, report: ValidationReport, section: str) -> str:
    kept = []
    for s in SENTENCE_RE.split(text.strip()):
        if SEVERITY_RE.search(s) or RECOMMEND_RE.search(s):
            report.removed_sentences.append(f"{section}: {s}")
            continue
        if INTERPRET_RE.search(s):
            report.interpretation_flags.append(f"{section}: {s}")
        kept.append(s)
    return " ".join(kept)


def validate_section(
    text: str, allowed_ids: set[str], self_refs: set[str], report: ValidationReport, section: str = ""
) -> tuple[str, list[str]]:
    """Validate inline citations and identifiers in one text field."""
    cited: list[str] = []
    text = _bare_ids_to_brackets(text, allowed_ids)

    def repl(m: re.Match) -> str:
        ids = [x.strip() for x in re.split(r"[,;]", m.group(1))]
        good = [i for i in ids if i in allowed_ids]
        for i in ids:
            if i not in allowed_ids and i not in report.invalid_citations:
                report.invalid_citations.append(i)
        for g in good:
            if g not in cited:
                cited.append(g)
        return f"[{', '.join(good)}]" if good else "[unsupported citation removed]"

    text = BRACKET_RE.sub(repl, text)

    # A sentence whose only support was a fabricated citation is an unsupported claim: drop it.
    kept = []
    for s in SENTENCE_RE.split(text.strip()):
        if "[unsupported citation removed]" in s and not BRACKET_RE.search(s):
            report.removed_sentences.append(f"{section}: {s} (only unsupported citations)")
            continue
        kept.append(s)
    text = " ".join(kept)

    def redact(m: re.Match) -> str:
        if m.group(1) in self_refs:
            return m.group(0)
        report.redacted_identifiers.append(m.group(1))
        return "[other identifier removed]"

    text = PATIENT_REF_RE.sub(redact, text)
    return text.strip(), cited


def count_uncited(text: str) -> tuple[int, int]:
    sentences = [s for s in SENTENCE_RE.split(text.strip()) if len(s.split()) >= 3]
    uncited = [s for s in sentences if not BRACKET_RE.search(s)]
    return len(sentences), len(uncited)


def strip_citations(text: str) -> str:
    return BRACKET_RE.sub(" ", text)


